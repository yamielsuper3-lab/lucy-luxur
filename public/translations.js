// Global variables to hold active language state
let currentLanguage = localStorage.getItem('lang') || 'es';

function setLanguage(lang) {
    currentLanguage = lang;
    localStorage.setItem('lang', lang);
    applyUITranslations(lang);
    
    // Dispatch custom event to let page scripts react to language change
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { language: lang } }));
}

function applyUITranslations(lang) {
    const dict = TRANSLATIONS_UI[lang] || TRANSLATIONS_UI['es'];
    
    // 1. Translate all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                el.placeholder = dict[key];
            } else {
                // If it contains HTML elements inside, preserve them if it's a button or span
                const hasHtml = el.querySelector('span') || el.querySelector('svg');
                if (hasHtml && key.startsWith('btn-') && el.querySelector('span')) {
                    el.querySelector('span').textContent = dict[key].replace(/👑|💳|🔒|✦/g, '').trim();
                } else {
                    if (dict[key].includes('<') && dict[key].includes('>')) {
                        el.innerHTML = dict[key];
                    } else {
                        el.textContent = dict[key];
                    }
                }
            }
        }
    });

    // 2. Manage active toggle button styling if present
    document.querySelectorAll('.lang-btn').forEach(btn => {
        const btnLang = btn.getAttribute('data-lang');
        if (btnLang === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
}

// Auto-run on document ready
document.addEventListener('DOMContentLoaded', () => {
    applyUITranslations(currentLanguage);
});

